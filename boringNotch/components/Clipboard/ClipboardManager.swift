import AppKit
import Combine
import Defaults
import Foundation
import SwiftUI

@MainActor
public final class ClipboardManager: ObservableObject {
    public static let shared = ClipboardManager()

    @Published public var items: [ClipboardItem] = []
    @Published public var searchText: String = ""
    @Published public var selectedFilter: ClipboardItemType = .all
    @Published public var selectedIndex: Int = 0

    private var lastChangeCount: Int = NSPasteboard.general.changeCount
    private var pollTimer: Timer?
    private var previousApp: NSRunningApplication?
    private var settingsObservers = Set<AnyCancellable>()
    private let storageQueue = DispatchQueue(label: "app.dino.clipboard.history", qos: .utility)
    private var isLoadingHistory = false
    private var historyGeneration = 0

    private static var historyURL: URL {
        let directory = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return directory.appendingPathComponent(Bundle.main.bundleIdentifier ?? "Dino", isDirectory: true)
            .appendingPathComponent("clipboard-history.plist")
    }

    // Concealed types used by password managers (1Password, Bitwarden, Keychain, etc.)
    private let concealedTypeIdentifiers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.dstelt.bitwarden"
    ]

    private init() {
        if Defaults[.clipboardHistoryPersist] {
            loadHistory()
        }
        Defaults.publisher(.clipboardHistoryPersist, options: [])
            .receive(on: DispatchQueue.main)
            .sink { [weak self] change in
                Task { @MainActor in
                    guard change.newValue == Defaults[.clipboardHistoryPersist] else { return }
                    self?.setPersistenceEnabled(change.newValue)
                }
            }
            .store(in: &settingsObservers)
        Defaults.publisher(.clipboardHistoryMaxItems, options: [])
            .receive(on: DispatchQueue.main)
            .sink { [weak self] _ in
                Task { @MainActor in
                    self?.trimHistory()
                    self?.saveHistory()
                }
            }
            .store(in: &settingsObservers)
    }

    // MARK: - Monitoring

    public func startMonitoring() {
        guard Defaults[.clipboardHistoryEnabled], pollTimer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        pollTimer = Timer.scheduledTimer(withTimeInterval: 0.45, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.checkPasteboard()
            }
        }
    }

    public func stopMonitoring() {
        pollTimer?.invalidate()
        pollTimer = nil
        ClipboardPanelController.shared.hide()
    }

    private func trimHistory() {
        let limit = max(10, Defaults[.clipboardHistoryMaxItems])
        while items.count > limit, let index = items.lastIndex(where: { !$0.isPinned }) {
            items.remove(at: index)
        }
    }

    private func loadHistory() {
        isLoadingHistory = true
        historyGeneration += 1
        let generation = historyGeneration
        let url = Self.historyURL
        storageQueue.async { [weak self] in
            let saved = (try? Data(contentsOf: url)).flatMap { try? PropertyListDecoder().decode([ClipboardItem].self, from: $0) } ?? []
            Task { @MainActor [weak self] in
                guard let self, self.historyGeneration == generation, Defaults[.clipboardHistoryPersist] else { return }
                let current = self.items
                self.items = current + saved.filter { old in
                    !current.contains { item in
                        item.id == old.id || (item.stringValue != nil && item.stringValue == old.stringValue)
                            || (item.imageData != nil && item.imageData == old.imageData)
                    }
                }
                self.isLoadingHistory = false
                self.trimHistory()
                self.saveHistory()
            }
        }
    }

    private func setPersistenceEnabled(_ enabled: Bool) {
        historyGeneration += 1
        isLoadingHistory = false
        if enabled {
            saveHistory()
        } else {
            let url = Self.historyURL
            storageQueue.async {
                do {
                    if FileManager.default.fileExists(atPath: url.path) {
                        try FileManager.default.removeItem(at: url)
                    }
                } catch {
                    NSLog("Clipboard history removal failed: %@", error.localizedDescription)
                }
            }
        }
    }

    private func saveHistory() {
        guard Defaults[.clipboardHistoryPersist], !isLoadingHistory else { return }
        let snapshot = items
        let url = Self.historyURL
        storageQueue.async {
            do {
                try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
                let data = try PropertyListEncoder().encode(snapshot)
                try data.write(to: url, options: .atomic)
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            } catch {
                NSLog("Clipboard history save failed: %@", error.localizedDescription)
            }
        }
    }

    private func checkPasteboard() {
        guard Defaults[.clipboardHistoryEnabled] else { return }

        let pb = NSPasteboard.general
        let currentChangeCount = pb.changeCount
        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount

        // 1. Privacy filter: ignore sensitive password manager entries
        if let types = pb.types {
            for type in types {
                if concealedTypeIdentifiers.contains(type.rawValue) {
                    return
                }
            }
        }

        // Get currently frontmost app name if available
        let frontApp = NSWorkspace.shared.frontmostApplication
        let frontAppName = frontApp?.localizedName

        // 2. Parse Image
        if let image = NSImage(pasteboard: pb),
           let tiffData = image.tiffRepresentation,
           let bitmap = NSBitmapImageRep(data: tiffData),
           let pngData = bitmap.representation(using: .png, properties: [:]) {
            // Deduplicate if already top item
            if let first = items.first, first.type == .image, first.imageData == pngData {
                return
            }

            let newItem = ClipboardItem(
                type: .image,
                imageData: pngData,
                previewTitle: "Image (\(Int(image.size.width)) × \(Int(image.size.height)))",
                previewSubtitle: "\(ByteCountFormatter.string(fromByteCount: Int64(pngData.count), countStyle: .file))",
                sourceAppName: frontAppName,
                timestamp: Date()
            )
            insertItem(newItem)
            return
        }

        // 3. Parse String (Text / Link / Color)
        if let string = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !string.isEmpty {
            // Deduplicate if identical to top item
            if let first = items.first, first.stringValue == string {
                return
            }

            let type: ClipboardItemType
            let title: String
            let subtitle: String

            if let url = URL(string: string), url.scheme == "http" || url.scheme == "https" {
                type = .link
                title = url.host ?? string
                subtitle = string
            } else if isHexColor(string) {
                type = .color
                title = string.uppercased()
                subtitle = "HEX Color code"
            } else {
                type = .text
                let lines = string.components(separatedBy: .newlines).filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
                title = lines.first ?? string
                subtitle = lines.count > 1 ? "\(lines.count) lines, \(string.count) characters" : "\(string.count) characters"
            }

            let newItem = ClipboardItem(
                type: type,
                stringValue: string,
                previewTitle: title,
                previewSubtitle: subtitle,
                sourceAppName: frontAppName,
                timestamp: Date()
            )
            insertItem(newItem)
            return
        }
    }

    private func isHexColor(_ str: String) -> Bool {
        let clean = str.trimmingCharacters(in: CharacterSet(charactersIn: "#"))
        guard clean.count == 6 || clean.count == 8 || clean.count == 3 else { return false }
        return clean.allSatisfy { $0.isHexDigit }
    }

    private func insertItem(_ item: ClipboardItem) {
        var item = item
        if items.contains(where: { existing in
            existing.isPinned && ((existing.stringValue != nil && existing.stringValue == item.stringValue)
                || (existing.imageData != nil && existing.imageData == item.imageData))
        }) {
            item.isPinned = true
        }
        // If exact item already exists, remove it first so it moves to top
        items.removeAll { existing in
            if let s1 = existing.stringValue, let s2 = item.stringValue, s1 == s2 {
                return true
            }
            if let d1 = existing.imageData, let d2 = item.imageData, d1 == d2 {
                return true
            }
            return false
        }

        items.insert(item, at: 0)

        trimHistory()
        saveHistory()
    }

    // MARK: - Filtered Items

    public var filteredItems: [ClipboardItem] {
        var result = items

        if selectedFilter != .all {
            result = result.filter { $0.type == selectedFilter }
        }

        if !searchText.isEmpty {
            let query = searchText.lowercased()
            result = result.filter {
                $0.previewTitle.lowercased().contains(query) ||
                $0.previewSubtitle.lowercased().contains(query) ||
                ($0.stringValue?.lowercased().contains(query) ?? false) ||
                ($0.sourceAppName?.lowercased().contains(query) ?? false)
            }
        }

        return result
    }

    // MARK: - Item Actions

    public func selectAndPaste(item: ClipboardItem) {
        let pb = NSPasteboard.general
        pb.clearContents()

        if let str = item.stringValue {
            pb.setString(str, forType: .string)
        } else if let imgData = item.imageData, let image = NSImage(data: imgData) {
            pb.writeObjects([image])
        }

        lastChangeCount = pb.changeCount

        // Close floating panel
        ClipboardPanelController.shared.hide()

        // Auto paste into previous application if enabled
        if Defaults[.clipboardHistoryAutoPaste] {
            Task { @MainActor in
                try? await Task.sleep(for: .milliseconds(120))
                self.simulatePasteKeystroke()
            }
        }
    }

    public func togglePin(item: ClipboardItem) {
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            items[idx].isPinned.toggle()
            trimHistory()
            saveHistory()
        }
    }

    public func removeItem(item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        saveHistory()
    }

    public func clearAll() {
        // Keep pinned items, delete unpinned
        items.removeAll { !$0.isPinned }
        saveHistory()
    }

    public func pickColorFromScreen() {
        ClipboardPanelController.shared.hide()

        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            let sampler = NSColorSampler()
            sampler.show { [weak self] selectedColor in
                Task { @MainActor in
                    guard let self = self else { return }
                    if let color = selectedColor,
                       let rgbColor = color.usingColorSpace(.sRGB) {
                        let r = Int(round(rgbColor.redComponent * 255))
                        let g = Int(round(rgbColor.greenComponent * 255))
                        let b = Int(round(rgbColor.blueComponent * 255))
                        let hex = String(format: "#%02X%02X%02X", r, g, b)

                        let pb = NSPasteboard.general
                        pb.clearContents()
                        pb.setString(hex, forType: .string)
                        self.lastChangeCount = pb.changeCount

                        let newItem = ClipboardItem(
                            type: .color,
                            stringValue: hex,
                            previewTitle: hex,
                            previewSubtitle: "HEX Color code",
                            sourceAppName: "Color Picker",
                            timestamp: Date()
                        )
                        self.insertItem(newItem)
                    }

                    // Re-open panel so user sees the newly picked color
                    ClipboardPanelController.shared.show()
                }
            }
        }
    }

    public func rememberPreviousApp() {
        let front = NSWorkspace.shared.frontmostApplication
        if front?.bundleIdentifier != Bundle.main.bundleIdentifier {
            previousApp = front
        }
    }

    private func simulatePasteKeystroke() {
        // Activate previous application
        previousApp?.activate(options: [.activateIgnoringOtherApps])

        DispatchQueue.main.asyncAfter(deadline: .now() + 0.1) {
            let src = CGEventSource(stateID: .combinedSessionState)
            // Keycode 9 is 'V'
            let cmdDown = CGEvent(keyboardEventSource: src, virtualKey: 0x09, keyDown: true)
            cmdDown?.flags = .maskCommand
            let cmdUp = CGEvent(keyboardEventSource: src, virtualKey: 0x09, keyDown: false)
            cmdUp?.flags = .maskCommand

            cmdDown?.post(tap: .cghidEventTap)
            cmdUp?.post(tap: .cghidEventTap)
        }
    }
}
